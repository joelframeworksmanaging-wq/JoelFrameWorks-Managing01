-- Joel Frame Work guest checkout database setup
-- Review before running in Supabase SQL Editor.
-- No customer Auth account is created; customers submit an order as anon.

create table if not exists public.customer_orders (
  id bigint generated by default as identity primary key,
  order_id text not null unique,
  order_type text not null check (order_type in ('product','combo')),
  customer_name text not null,
  customer_phone text not null,
  customer_address text not null,
  total_price numeric(10,2) not null check (total_price > 0),
  order_details jsonb not null default '{}'::jsonb,
  image_links jsonb not null default '[]'::jsonb,
  status text not null default 'payment_pending',
  payment_status text not null default 'pending',
  razorpay_order_id text,
  razorpay_payment_id text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.customer_orders
  add column if not exists status text not null default 'payment_pending',
  add column if not exists payment_status text not null default 'pending',
  add column if not exists razorpay_order_id text,
  add column if not exists razorpay_payment_id text,
  add column if not exists updated_at timestamptz not null default now();

create unique index if not exists customer_orders_order_id_uidx
  on public.customer_orders(order_id);
create index if not exists customer_orders_created_at_idx
  on public.customer_orders(created_at desc);
create index if not exists customer_orders_razorpay_order_id_idx
  on public.customer_orders(razorpay_order_id);

alter table public.customer_orders enable row level security;

drop policy if exists "Guest checkout can create orders" on public.customer_orders;
create policy "Guest checkout can create orders"
  on public.customer_orders
  for insert
  to anon
  with check (
    length(trim(customer_name)) between 2 and 120
    and length(regexp_replace(customer_phone, '[^0-9]', '', 'g')) between 10 and 13
    and length(trim(customer_address)) between 8 and 1000
    and total_price > 0
    and order_type in ('product','combo')
  );

drop policy if exists "Authenticated admins manage customer orders" on public.customer_orders;
create policy "Authenticated admins manage customer orders"
  on public.customer_orders
  for all
  to authenticated
  using (true)
  with check (true);

-- Current guest upload code writes files under orders/<order-id>/...
-- The media bucket is currently public in supabase-schema.sql, so uploaded
-- image URLs are publicly readable. Restrict anonymous upload to the orders
-- folder; before production, migrate order photos to a private bucket and
-- generate short-lived signed URLs for the admin portal.
drop policy if exists "Guest checkout can upload order photos" on storage.objects;
create policy "Guest checkout can upload order photos"
  on storage.objects
  for insert
  to anon
  with check (
    bucket_id = 'joel-site-media'
    and (storage.foldername(name))[1] = 'orders'
  );

